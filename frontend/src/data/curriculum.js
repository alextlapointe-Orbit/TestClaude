export const getTotalLessons = () =>
  MODULES.reduce((sum, m) => sum + m.lessons.length, 0)

export const getLessonById = (id) => {
  for (const mod of MODULES) {
    const lesson = mod.lessons.find((l) => l.id === id)
    if (lesson) return { module: mod, lesson }
  }
  return null
}
